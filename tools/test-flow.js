// first-time player flow: title -> launch -> run -> build -> map -> recruit -> goals
const H = require('./helpers');
module.exports = async (page) => {
  const SP = process.env.SP;
  const st = () => page.evaluate(() => ({ scene: DH.G.sceneName, panel: DH.G.panel && DH.G.panel.kind, tip: DH.Prog.currentTip() && DH.Prog.currentTip().id, res: DH.G.state && DH.G.state.res, runs: DH.G.state && DH.G.state.stats.runs }));
  await page.waitForTimeout(900);
  await H.tapAnywhere(page);
  await page.waitForTimeout(900);
  await page.screenshot({ path: SP + '/f1_welcome.png' });
  console.log('1', JSON.stringify(await st()));
  await H.hit(page, 'bar:launch');
  await page.waitForTimeout(800);
  await H.autoMine(page, 9000);
  await page.screenshot({ path: SP + '/f2_run.png' });
  await page.evaluate(() => { DH.Scenes.run.debug().drone.fuel = 0.3; });
  await page.waitForTimeout(5500);
  await page.screenshot({ path: SP + '/f3_tally.png' });
  await H.hit(page, 'run:continue');
  await page.waitForTimeout(900);
  console.log('2', JSON.stringify(await st()));
  await page.evaluate(() => { DH.G.state.res.cu = Math.max(DH.G.state.res.cu, 9); DH.G.state.res.ice = Math.max(DH.G.state.res.ice, 5); });
  await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/f4_buildtip.png' });
  await H.hit(page, 'room:1');
  await page.waitForTimeout(500);
  await page.screenshot({ path: SP + '/f5_buildpanel.png' });
  await H.hit(page, 'build:quarters');
  await page.waitForTimeout(1200);
  console.log('3', JSON.stringify(await st()));
  await page.screenshot({ path: SP + '/f6_maptip.png' });
  await H.hit(page, 'bar:map');
  await page.waitForTimeout(900);
  await page.screenshot({ path: SP + '/f7_map.png' });
  await H.hit(page, 'pl:kettle');
  await page.waitForTimeout(600);
  await page.screenshot({ path: SP + '/f8_planet.png' });
  await H.hit(page, 'rec:');
  await page.waitForTimeout(600);
  console.log('4', JSON.stringify(await st()));
  await H.hit(page, 'ptab:2');
  await page.waitForTimeout(300);
  await page.screenshot({ path: SP + '/f9_shop.png' });
  await H.hit(page, 'panelclose');
  await H.hit(page, 'bar:ship');
  await page.waitForTimeout(1500);
  await page.screenshot({ path: SP + '/f10_goals.png' });
  console.log('5', JSON.stringify(await st()));
  await H.tapAnywhere(page);
  await page.waitForTimeout(800);
  await page.screenshot({ path: SP + '/f11_ship.png' });
  console.log('6', JSON.stringify(await page.evaluate(() => DH.G.state.goals.map(g => DH.Prog.goalText(g)))));
};
