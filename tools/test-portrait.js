const H = require('./helpers');
module.exports = async (page) => {
  const SP = process.env.SP;
  await page.evaluate(() => {
    const s = DH.Save.defaultState();
    s.hull = 7; s.revealed = 3;
    s.slots = [{ type: 'bridge', lvl: 3 }, { type: 'quarters', lvl: 3 }, { type: 'workshop', lvl: 2 }, { type: 'hydroponics', lvl: 2 }, { type: 'refinery', lvl: 2 }, { type: 'observatory', lvl: 2 }, null];
    s.slots.forEach(r => r && (r.decor = null));
    Object.assign(s.res, { cu: 220, ice: 180, cry: 40, food: 90, alloy: 30, data: 12 });
    s.seen.ores = { cu: true, ice: true, cry: true }; s.seen.sectors = { 1: true, 2: true, 3: true };
    ['quarters', 'workshop', 'hydroponics', 'refinery', 'observatory', 'galley', 'lab'].forEach(t => s.blueprints[t] = true);
    for (let i = 0; i < 4; i++) { const c = DH.Crew.generate('p' + i, 'kettle'); c.room = i < 3 ? 2 + i : null; s.crew.push(c); s.seen.traits[c.trait] = { name: c.name, look: c.look }; }
    s.visited = { kettle: 1, moss: 1 };
    s.stats.runs = 9; s.stats.partsBuilt = 3;
    s.unlocked = { ship: true, launch: true, map: true, log: true, goals: true, daily: true };
    ['welcome', 'build1', 'map', 'visit', 'goals', 'expand', 'workshop', 'assign', 'log', 'food', 'daily', 'refinery', 'travel'].forEach(k => s.tut.done[k] = true);
    s.tut.done.logOpened = true; s.tut.done.dailySeen = true;
    localStorage.setItem('drifthold.save', JSON.stringify(s));
  });
  await page.reload();
  await page.waitForTimeout(900);
  await H.tapAnywhere(page);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: SP + '/p1_ship.png' });
  await H.hit(page, 'room:2'); await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/p2_workshop.png' });
  await H.hit(page, 'rtab:1'); await page.waitForTimeout(300);
  await page.screenshot({ path: SP + '/p3_room.png' });
  await H.hit(page, 'panelclose');
  await H.hit(page, 'room:6'); await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/p4_build.png' });
  await H.hit(page, 'panelclose');
  await H.hit(page, 'bar:map'); await page.waitForTimeout(900);
  await page.screenshot({ path: SP + '/p5_map.png' });
  await H.hit(page, 'pl:moss'); await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/p6_planet.png' });
  await H.hit(page, 'ptab:1'); await page.waitForTimeout(300);
  await page.screenshot({ path: SP + '/p7_trade.png' });
  await H.hit(page, 'panelclose');
  await H.hit(page, 'bar:launch'); await page.waitForTimeout(400);
  await H.hit(page, 'l:normal'); await page.waitForTimeout(1500);
  await H.autoMine(page, 3000);
  await page.screenshot({ path: SP + '/p8_run.png' });
  await page.evaluate(() => { DH.Scenes.run.debug().drone.fuel = 0.1; });
  await page.waitForTimeout(6000);
  await page.screenshot({ path: SP + '/p9_tally.png' });
  await H.hit(page, 'run:continue'); await page.waitForTimeout(800);
  await H.hit(page, 'bar:settings'); await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/p10_settings.png' });
};
